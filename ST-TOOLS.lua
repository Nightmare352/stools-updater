			arm_sp = text:match('arm%p%s(%d+)')
        	local found_ip = text:match("ip[%s:]+(%d+%.%d+%.%d+%.%d+)")
			if found_ip then
				ip_sp = found_ip
			end
        	version_sp = text:match('version%p%s(%d+)')
		end
	return false
	end
end
