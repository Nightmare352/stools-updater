function keySyncStart(playerId)
    if type(playerId) ~= "number" then
        return false
    end
    if playerId == -1 then
        return false
    end
    if not sampIsPlayerConnected(playerId) then
        return false
    end

    local _, myId = sampGetPlayerIdByCharHandle(PLAYER_PED)
    if playerId == myId then
        keySyncStop()
        return false
    end

    local ok, ped = sampGetCharHandleBySampPlayerId(playerId)
    if not ok or not ped or not doesCharExist(ped) then
        keySyncStop()
        return false
    end

    keySync.target = ped
    keySync.enabled = true
    return true
end
function keySyncStop()
    keySync.enabled = false
    keySync.target = -1
    keySync.keys.onfoot = {}
    keySync.keys.vehicle = {}
end
function keySyncIsValid()
    if not keySync.enabled then
        return false
    end
    if keySync.target == nil or keySync.target == -1 then
        keySyncStop()
        return false
    end
    if not doesCharExist(keySync.target) then
        keySyncStop()
        return false
    end
    return true
end
